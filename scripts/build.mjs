/**
 * Builds the two artifacts this package ships:
 *
 *   lib/client.js      the browser bundle the Host serves at
 *                      /plugins/dsh-balance-gauge/client.js (lazy-CJS factory
 *                      form the client module system expects)
 *   preview/index.html an offline render of the same markup and CSS, used to
 *                      eyeball the widget without restarting the GUI
 *
 * No bundler: the sources are small, dependency-free ES modules, so this
 * script inlines them and fails loudly on anything it cannot handle.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')

/** Turn the ES module into factory-scope statements. */
function inlineModule(source) {
  if (/^\s*import\s/m.test(source)) throw new Error('gauge.js must stay dependency-free')
  const stripped = source.replace(/^export\s+(const|let|function|class)\s/gm, '$1 ')
  if (/^\s*export\s/m.test(stripped)) throw new Error('gauge.js has an export form this build cannot inline')
  return stripped
}

const gauge = inlineModule(read('src/gauge.js'))
const css = read('src/gauge.css')
const client = read('src/client.js')

const STYLE_BLOCK = `
		const CSS_TEXT = ${JSON.stringify(css)}
		const CSS_TAG_ID = 'dsh-balance-gauge/gauge.css'
		if (
			typeof document !== 'undefined' &&
			document.querySelector('style[data-plugin-css=' + JSON.stringify(CSS_TAG_ID) + ']') === null
		) {
			const tag = document.createElement('style')
			tag.dataset.plugin = 'dsh-balance-gauge'
			tag.dataset.pluginCss = CSS_TAG_ID
			tag.textContent = CSS_TEXT
			document.head.appendChild(tag)
		}
`

const bundle = `/* dsh-balance-gauge — generated by scripts/build.mjs, do not edit. */
window.__ModuleLoader__.load({
	id: "dsh-balance-gauge",
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
		const React = require("react");
${STYLE_BLOCK}
${gauge}
${client}
		exports.apply = apply;
		exports.inject = inject;
		return module.exports;
	}
});
`

fs.mkdirSync(path.join(root, 'lib'), { recursive: true })
fs.writeFileSync(path.join(root, 'lib/client.js'), bundle)
console.log(`lib/client.js  ${Buffer.byteLength(bundle)} bytes`)

