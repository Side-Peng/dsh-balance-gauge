/** The markup the React component emits, rendered with the shipped helpers. */
function rowHtml(sample) {
  const ready = sample.phase === 'ready'
  const zone = ready ? gaugeLib.zoneOf(sample.amount) : 'unknown'
  const percent = ready ? gaugeLib.percentOf(sample.amount) : 0
  const copy = gaugeLib.COPY[ready ? zone : sample.phase] || gaugeLib.COPY.loading
  const amount = ready ? gaugeLib.formatMoney(sample.amount, sample.currency) : sample.phase === 'loading' ? '···' : '--'
  const speed = sample.speed ?? 0
  const speedKnown = sample.speedKnown !== false
  const ink = gaugeLib.ZONE_INK[zone]
  const inkStyle = ink ? ` style="--bg-zone-ink:${ink}"` : ''
  return (
    `<div class="sample"><div class="sample-label">${sample.label}</div>` +
    `<div class="bg-root"><div class="bg-card" data-zone="${zone}" data-phase="${sample.phase}"${inkStyle}>` +
    `<span class="bg-cell">` +
    `<span class="bg-dial-host">${gaugeLib.dialSvg({ percent, zone, dim: !ready })}</span>` +
    `<span class="bg-readout"><span class="bg-amount bg-amount--money">${amount}</span>` +
    `<span class="bg-sub">${copy.emoji} ${copy.text}</span></span>` +
    `</span>` +
    `<span class="bg-divider"></span>` +
    `<span class="bg-cell">` +
    `<span class="bg-dial-host">${gaugeLib.speedDialSvg({ percent: gaugeLib.speedPercent(speed), dim: !speedKnown })}</span>` +
    `<span class="bg-readout"><span class="bg-amount bg-amount--speed">${gaugeLib.formatSpeed(speed)}</span>` +
    `<span class="bg-sub">tok/s</span></span>` +
    `</span>` +
    `</div></div></div>`
  )
}

